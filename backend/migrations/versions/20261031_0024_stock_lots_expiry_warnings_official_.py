def _backfill_lots() -> None:
    bind = op.get_bind()
    balances = list(
        bind.execute(
            sa.text(
                "SELECT b.item_id, b.warehouse_id, b.qty FROM stock_balance b "
                "JOIN item i ON i.id = b.item_id WHERE i.track_expiry = 1 AND b.qty > 0"
            )
        )
    )
    for item_id, wh_id, qty in balances:
        receipts = list(
            bind.execute(
                sa.text(
                    "SELECT l.qty_in, d.expiry_date, l.document_date FROM stock_ledger l "
                    "JOIN stock_document_line d ON d.id = l.document_line_id "
                    "WHERE l.item_id = :i AND l.warehouse_id = :w AND l.qty_in > 0 "
                    "ORDER BY l.document_date DESC, l.seq DESC"
                ),
                {"i": item_id, "w": wh_id},
            )
        )
        lots: dict[object, list] = {}
        left = qty
        for got, expiry, on in receipts:
            if left <= 0:
                break
            take = min(got, left)
            left -= take
            lot = lots.setdefault(expiry, [0, on])
            lot[0] += take
            lot[1] = min(lot[1], on)
        if left > 0:
            lot = lots.setdefault(None, [0, receipts[-1][2] if receipts else date.today()])
            lot[0] += left
        for expiry, (q, on) in lots.items():
            bind.execute(
                sa.text(
                    "INSERT INTO stock_lot (id, item_id, warehouse_id, expiry_date, qty, "
                    "first_received) VALUES (NEWID(), :i, :w, :e, :q, :o)"
                ),
                {"i": item_id, "w": wh_id, "e": expiry, "q": q, "o": on},
            )


