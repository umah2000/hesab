    manual_discount_percent: Decimal
    discount_limit_percent: Decimal
    needs_discount_approval: bool
    warnings: list[str]

    @field_serializer("manual_discount_percent", "discount_limit_percent")
    def _pct(self, v: Decimal) -> str:
        return _rate(v)


